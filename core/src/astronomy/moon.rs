#[cfg(test)]
mod tests {
    use super::*;
    use crate::astronomy::constants::to_deg;

    /// Meeus Example 47.a — 1992 Apr 12, JDE 2448724.5
    #[test]
    fn moon_1992_apr_12() {
        let jde = 2_448_724.5;
        let pos = lunar_position(jde);
        let lon_deg = to_deg(pos.lon);
        let lat_deg = to_deg(pos.lat);
        // Expected: lon ≈ 133.167°, lat ≈ -3.229°, dist ≈ 368409 km
        assert!((lon_deg - 133.167).abs() < 0.1, "Moon lon = {lon_deg}");
        assert!((lat_deg - (-3.229)).abs() < 0.05, "Moon lat = {lat_deg}");
        assert!(
            (pos.dist_km - 368_409.0).abs() < 200.0,
            "Moon dist = {}",
            pos.dist_km
        );
    }

    #[test]
    fn moon_returns_finite_j2000() {
        let pos = lunar_position(2_451_545.0);
        assert!(pos.lon.is_finite());
        assert!(pos.lat.is_finite());
        assert!(pos.dist_km > 350_000.0 && pos.dist_km < 410_000.0);
    }
}
