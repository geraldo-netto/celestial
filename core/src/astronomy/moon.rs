//! Lunar theory — truncated ELP2000-82 (Chapront & Chapront-Touzé 1983).
//!
//! Gives geocentric ecliptic longitude, latitude and distance of the Moon.
//! Accuracy: ~10" in longitude, ~4" in latitude, ~4 km in distance.
//!
//! Reference: Meeus, "Astronomical Algorithms" 2nd ed., Chapter 47.

use crate::astronomy::constants::{julian_centuries, norm_rad, to_rad};

/// Geocentric lunar coordinates.
#[derive(Debug, Clone, Copy)]
pub struct LunarPos {
    /// Geocentric ecliptic longitude (radians).
    pub lon: f64,
    /// Geocentric ecliptic latitude (radians).
    pub lat: f64,
    /// Earth–Moon distance (km).
    pub dist_km: f64,
}

/// Compute the Moon's geocentric ecliptic position for a given JDE (TT).
#[inline]
#[must_use]
pub fn lunar_position(jde: f64) -> LunarPos {
    let t = julian_centuries(jde);

    // ── Fundamental arguments (degrees) ──────────────────────────────────────
    // Moon's mean longitude
    let lp = 218.316_447_7 + 481_267.881_234_21 * t - 0.001_578_6 * t * t + t * t * t / 538_841.0
        - t * t * t * t / 65_194_000.0;

    // Moon's mean anomaly (M')
    let m_prime =
        134.962_981_4 + 477_198.867_505_5 * t + 0.008_741_4 * t * t + t * t * t / 69_699.0
            - t * t * t * t / 14_712_000.0;

    // Sun's mean anomaly (M)
    let m_sun =
        357.529_109_2 + 35_999.050_290_9 * t - 0.000_153_6 * t * t + t * t * t / 24_490_000.0;

    // Moon's argument of latitude (F)
    let f = 93.272_095_0 + 483_202.017_523_3 * t - 0.003_636_9 * t * t - t * t * t / 3_526_000.0
        + t * t * t * t / 863_310_000.0;

    // Longitude of the ascending node of Moon's orbit (Ω)
    // omega (Moon's ascending node) is not used in the truncated ELP terms below;
    // it is left out intentionally — the contribution would be < 1″ for the Moon's
    // longitude in the orders kept here.

    // Additional arguments E, A1, A2, A3
    let e = 1.0 - 0.002_516 * t - 0.000_007_4 * t * t;
    let e2 = e * e;

    let a1 = 119.75 + 131.849 * t;
    let a2 = 53.09 + 479_264.290 * t;
    let a3 = 313.45 + 481_266.484 * t;

    // Moon's mean elongation (D) — Meeus Chapter 47
    let d_elong = 297.850_363_0 + 445_267.111_480 * t - 0.001_914_2 * t * t + t * t * t / 545_868.0
        - t * t * t * t / 113_065_000.0;

    // Convert to radians
    let d_r = to_rad(d_elong);
    let lp_r = to_rad(lp);
    let mp_r = to_rad(m_prime);
    let ms_r = to_rad(m_sun);
    let f_r = to_rad(f);
    let a1_r = to_rad(a1);
    let a2_r = to_rad(a2);
    let a3_r = to_rad(a3);

    // ── Sum of longitude/distance terms ──────────────────────────────────────
    let mut sum_l = 0.0_f64; // × 10⁻⁶ degrees
    let mut sum_r = 0.0_f64; // × 10⁻³ km

    for &[dc, mc, mpc, fc, sl, sr] in LONGITUDE_DISTANCE_TERMS {
        let arg = dc * d_r + mc * ms_r + mpc * mp_r + fc * f_r;
        // Apply E correction for terms involving M or 2M
        let e_factor = match mc.abs() as i32 {
            1 => e,
            2 => e2,
            _ => 1.0,
        };
        // sin_cos pairs the two evaluations into one transcendental call
        // (`fsincos` on x86, `sincos` libm intrinsic on others).
        let (sin_arg, cos_arg) = arg.sin_cos();
        sum_l += sl * e_factor * sin_arg;
        sum_r += sr * e_factor * cos_arg;
    }

    // ── Additive corrections to longitude ────────────────────────────────────
    sum_l += 3958.0 * a1_r.sin() + 1962.0 * (lp_r - f_r).sin() + 318.0 * a2_r.sin();

    // ── Sum of latitude terms ─────────────────────────────────────────────────
    let mut sum_b = 0.0_f64; // × 10⁻⁶ degrees

    for &[dc, mc, mpc, fc, sb] in LATITUDE_TERMS {
        let arg = dc * d_r + mc * ms_r + mpc * mp_r + fc * f_r;
        let e_factor = match mc.abs() as i32 {
            1 => e,
            2 => e2,
            _ => 1.0,
        };
        sum_b += sb * e_factor * arg.sin();
    }

    // ── Additive corrections to latitude ─────────────────────────────────────
    sum_b += -2235.0 * lp_r.sin()
        + 382.0 * a3_r.sin()
        + 175.0 * (a1_r - f_r).sin()
        + 175.0 * (a1_r + f_r).sin()
        + 127.0 * (lp_r - mp_r).sin()
        - 115.0 * (lp_r + mp_r).sin();

    // ── Convert to final coordinates ─────────────────────────────────────────
    let lon_deg = lp + sum_l / 1_000_000.0;
    let lat_deg = sum_b / 1_000_000.0;
    let dist_km = 385_000.56 + sum_r / 1_000.0;

    LunarPos {
        lon: norm_rad(to_rad(lon_deg)),
        lat: to_rad(lat_deg),
        dist_km,
    }
}

