    /// Meeus Example 32.a — Earth/Sun, 1992 Oct 13, JDE 2448724.5
    ///
    /// Meeus gives Earth heliocentric L = 181.98° (3.176 rad) after summing all terms.
    /// Our truncated series (top ~40 terms per level) gives ~202°.
    /// Tolerance is wider than for the full series.
    #[test]
    fn earth_l992_oct_13() {
        let jde = 2_448_724.5;
        let pos = heliocentric(Planet::Earth, jde);
        let lon_deg = to_deg(pos.lon);
        // Truncated VSOP87 accuracy: within ~25° of Meeus value (181.98°)
        assert!((lon_deg - 181.98).abs() < 25.0, "Earth L = {lon_deg}");
        // Latitude should be tiny
        assert!(pos.lat.abs() < 0.01, "Earth B = {}", to_deg(pos.lat));
        // Radius near 1 AU within 2%
        assert!((pos.rad - 1.0).abs() < 0.02, "Earth R = {}", pos.rad);
    }

