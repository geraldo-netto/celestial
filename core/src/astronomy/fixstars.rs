const J2000: f64 = 2451545.0;
const ARCSEC_TO_DEG: f64 = 1.0 / 3600.0;

/// Look up a star by name (case-insensitive, matches name or bayer designator).
/// Returns the index into CATALOG, or None.
///
/// Matching is case-insensitive: exact name or Bayer designation first,
/// then prefix match on the common name.
pub fn find_star(query: &str) -> Option<usize> {
    let q = query.trim();
    // Hoist case-fold once instead of re-folding per catalog row.
    let q_lower = q.to_ascii_lowercase();
    // Single pass: exact match first (avoids a second scan in the common case)
    let mut prefix_match: Option<usize> = None;
    for (i, s) in CATALOG.iter().enumerate() {
        if s.name.eq_ignore_ascii_case(q) || s.bayer.eq_ignore_ascii_case(q) {
            return Some(i); // exact hit — return immediately
        }
        // Prefix check: case-insensitive, but allocation-free using bytewise
        // compare of the already-lowercased query against the catalog name.
        if prefix_match.is_none()
            && s.name.len() >= q_lower.len()
            && s.name
                .as_bytes()
                .iter()
                .zip(q_lower.as_bytes())
                .all(|(a, b)| a.to_ascii_lowercase() == *b)
        {
            prefix_match = Some(i);
        }
    }
    prefix_match
}

/// Apparent ecliptic position of a fixed star at a given JDE (UT).
///
/// Returns `(ecliptic_lon_deg, ecliptic_lat_deg, distance_au)`.
/// Applies precession and proper motion only (no parallax for distant stars).
pub fn star_ecliptic_pos(star: &StarEntry, jd_ut: f64) -> (f64, f64, f64) {
    let t = (jd_ut - J2000) / 365.25; // Julian years from J2000

    // Apply proper motion (arcsec/yr → degrees)
    let ra = star.ra + t * star.pm_ra * ARCSEC_TO_DEG;
    let dec = star.dec + t * star.pm_dec * ARCSEC_TO_DEG;

    // Equatorial → ecliptic (J2000 obliquity 23.4393°)
    let eps = 23.4393_f64.to_radians();
    let ra_r = ra.to_radians();
    let dec_r = dec.to_radians();

    // Meeus eq 13.1: ecliptic latitude
    let (sin_ra, cos_ra) = ra_r.sin_cos();
    let (sin_dec, cos_dec) = dec_r.sin_cos();
    let (sin_eps, cos_eps) = eps.sin_cos();
    let lat_r = (-cos_dec * sin_eps)
        .mul_add(sin_ra, sin_dec * cos_eps)
        .clamp(-1.0, 1.0)
        .asin();
    // Ecliptic longitude: atan2(y, x) where y and x give quadrant
    let y_lon = (sin_eps * sin_dec).mul_add(1.0, sin_ra * cos_eps * cos_dec);
    let x_lon = cos_ra * cos_dec;
    let lon_r = y_lon.atan2(x_lon);

    // Apply precession: ~50.29 arcsec/yr ≈ 0.01396°/yr.
    // rem_euclid normalises any negative or out-of-range value into [0, 360).
    let prec_rate = 0.013972_f64; // deg/year
    let lon = (lon_r.to_degrees() + t * prec_rate).rem_euclid(360.0);
    let lat = lat_r.to_degrees();
    let dist = if star.plx > 0.0 {
        1.0 / (star.plx / 1000.0) * 206_265.0
    } else {
        1.0e10
    };

    (lon, lat, dist)
}

/// Speed of a fixed star in ecliptic coordinates (deg/day).
/// For stars this is essentially just the precession rate, which is tiny.
pub fn star_speed(_star: &StarEntry) -> (f64, f64, f64) {
    // Precession in longitude: ~50.29 arcsec/yr → deg/day
    let speed_lon = 50.29 / 3600.0 / 365.25;
    (speed_lon, 0.0, 0.0)
}
