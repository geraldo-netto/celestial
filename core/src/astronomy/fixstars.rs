//! Built-in fixed star catalog.
//!
//! Positions are J2000.0 (ICRS) RA/Dec in degrees, with annual proper motion
//! in arcsec/year. Magnitudes are visual (V-band).
//!
//! Catalog sources: Hipparcos, Yale Bright Star Catalog, FK6.

/// One fixed star entry.
#[derive(Debug, Clone, PartialEq)]
pub struct StarEntry {
    /// Traditional name (e.g. "Sirius")
    pub name: &'static str,
    /// Bayer/Flamsteed designation (e.g. "alCMa")
    pub bayer: &'static str,
    /// Right ascension J2000, degrees
    pub ra: f64,
    /// Declination J2000, degrees
    pub dec: f64,
    /// Annual proper motion in RA  (arcsec / year)
    pub pm_ra: f64,
    /// Annual proper motion in Dec (arcsec / year)
    pub pm_dec: f64,
    /// Visual magnitude
    pub mag: f64,
    /// Parallax (arcsec) — used to compute distance in AU
    pub plx: f64,
    /// Radial velocity km/s (for completeness; negligible for most uses)
    pub rv: f64,
}

